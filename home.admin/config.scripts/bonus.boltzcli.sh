  sudo systemctl daemon-reload

  # remove binaries
  sudo rm -f /usr/local/bin/boltzd
  sudo rm -f /usr/local/bin/boltzcli

  # remove aliases
  sudo sed -i '/^alias boltzcli=/d' /home/admin/_aliases
  sudo sed -i '/^alias boltzlog=/d' /home/admin/_aliases

  # delete user
  sudo userdel -rf ${APPUSER} 2>/dev/null

  # mark as uninstalled in raspiblitz config
  /home/admin/config.scripts/blitz.conf.sh set ${APPID} "off"

  # handle data deletion
  if [ "$(echo "$@" | grep -c delete-data)" -gt 0 ]; then
    echo "# Deleting data directory ${BOLTZ_DATA_DIR}"
    sudo rm -rf "${BOLTZ_DATA_DIR}"
  else
    echo "# Keeping data directory ${BOLTZ_DATA_DIR}"
    echo "# To also delete data, run: bonus.boltzcli.sh off delete-data"
  fi

  echo "# OK - Boltz Client removed"
  exit 0
fi

