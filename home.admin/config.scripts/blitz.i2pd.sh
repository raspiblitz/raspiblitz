#!/bin/bash

# https://i2pd.readthedocs.io

if [ $# -eq 0 ] || [ "$1" = "-h" ] || [ "$1" = "-help" ]; then
  echo "I2P Daemon install script"
  echo "More info at https://i2pd.readthedocs.io"
  echo "Usage:"
  echo "blitz.i2pd.sh install      -> Install i2pd"
  echo "blitz.i2pd.sh on           -> Switch on i2pd"
  echo "blitz.i2pd.sh off          -> Uninstall i2pd"
  echo "blitz.i2pd.sh addseednodes -> Add 21 randonly selected I2P seed nodes from: https://github.com/bitcoin/bitcoin/blob/master/contrib/seeds/nodes_main.txt"
  echo "blitz.i2pd.sh status       -> I2P related logs from bitcoind, bitcoin-cli -netinfo 4 and webconsole access"
  exit 1
fi

function confAdd {
  # get parameters
  keystr="$1"
  valuestr=$(echo "$2" | sed 's/\//\\\//g')
  configFile="$3"

  # check if key needs to be added (prepare new entry)
  entryExists=$(grep -c "^${keystr}=" ${configFile})
  if [ ${entryExists} -eq 0 ]; then
    echo "${keystr}=" | sudo tee -a ${configFile} 1>/dev/null
  fi

  # add an extra key=value line (needs sudo to operate when user is not root)
  echo "${keystr}=${valuestr}" | sudo tee -a ${configFile}
}

function add_repo (
  # Add repo for the latest version
  # Preserve the existing upstream and distribution selection.

  source /etc/os-release
  DIST=$ID
  case $ID in
  debian | ubuntu | raspbian)
    if [[ -n $DEBIAN_CODENAME ]]; then
      VERSION_CODENAME=$DEBIAN_CODENAME
    fi
    if [[ -n $UBUNTU_CODENAME ]]; then
      VERSION_CODENAME=$UBUNTU_CODENAME
    fi
    if [[ -z $VERSION_CODENAME ]]; then
      echo "Couldn't find VERSION_CODENAME in your /etc/os-release file. Did your system supported? Please report issue to me by writing to email: 'r4sas <at> i2pd.xyz'"
      exit 1
    fi
    RELEASE=$VERSION_CODENAME
    ;;
  *)
    if [[ -z $ID_LIKE || "$ID_LIKE" != "debian" && "$ID_LIKE" != "ubuntu" ]]; then
      echo "Your system is not supported by this script. Currently it supports debian-like and ubuntu-like systems."
      exit 1
    else
      DIST=$ID_LIKE
      case $ID_LIKE in
      debian)
        if [[ "$ID" == "kali" ]]; then
          if [[ "$VERSION" == "2019"* || "$VERSION" == "2020"* ]]; then
            RELEASE="buster"
          elif [[ "$VERSION" == "2021"* || "$VERSION" == "2022"* ]]; then
            RELEASE="bullseye"
          fi
        else
          RELEASE=$DEBIAN_CODENAME
        fi
        ;;
      ubuntu)
        RELEASE=$UBUNTU_CODENAME
        ;;
      esac
    fi
    ;;
  esac
  if [[ -z $RELEASE ]]; then
    echo "Couldn't detect your system release. Please report issue to me by writing to email: 'r4sas <at> i2pd.xyz'"
    exit 1
  fi
  local fingerprint=951928BB317024EFD053D73C66F6C87B98EBCFE2
  local keyring=/etc/apt/keyrings/i2pd.gpg
  local legacy=/etc/apt/trusted.gpg.d/i2pd.gpg
  local list=/etc/apt/sources.list.d/i2pd.list
  local source="https://repo.i2pd.xyz/$DIST $RELEASE main"
  if [ -f "$list" ]; then
    # Only replace entries generated by RaspiBlitz. Preserve any administrator options or other archives.
    if ! awk -v src="$source" -v scoped="[signed-by=$keyring] " '
      /^[[:space:]]*(#|$)/ {next}
      {
        line=$0
        if (sub(/^(deb|deb-src)[[:space:]]+/, "", line) && (line==src || line==scoped src)) {
          managed=1
        } else {
          custom=1
        }
      }
      END {exit !(managed && !custom)}
    ' "$list"; then
      echo "# Custom i2pd APT source in $list. Preserve it and verify its Signed-By setting manually." >&2
      return 1
    fi
  fi
  local stage
  stage=$(mktemp -d) || return 1
  trap 'rm -rf -- "$stage"' EXIT

  curl --fail --silent --show-error --location --proto '=https' --proto-redir '=https' \
    https://repo.i2pd.xyz/r4sas.gpg -o "$stage/download" || return 1
  gpg --batch --homedir "$stage" --import "$stage/download" || return 1
  gpg --batch --homedir "$stage" --export "$fingerprint" >"$stage/i2pd.gpg" || return 1
  local exported
  exported=$(gpg --batch --homedir "$stage" --with-colons --show-keys "$stage/i2pd.gpg") || return 1
  if [ "$(awk -F: '$1=="pub" {pub=1} $1=="fpr" && pub {print $10; pub=0}' <<<"$exported")" != "$fingerprint" ]; then
    echo "# Missing expected i2pd archive key $fingerprint" >&2
    return 1
  fi

  printf '%s\n' "deb [signed-by=$keyring] https://repo.i2pd.xyz/$DIST $RELEASE main" \
    "deb-src [signed-by=$keyring] https://repo.i2pd.xyz/$DIST $RELEASE main" >"$stage/i2pd.list" || return 1
  # Verify the publisher can authenticate this suite before changing the active APT files.
  curl --fail --silent --show-error --location --proto '=https' --proto-redir '=https' \
    "https://repo.i2pd.xyz/$DIST/dists/$RELEASE/InRelease" -o "$stage/InRelease" || return 1
  gpgv --keyring "$stage/i2pd.gpg" "$stage/InRelease" >/dev/null || return 1
  printf '%s\n' 'Package: i2pd' 'Pin: origin "repo.i2pd.xyz"' 'Pin-Priority: 500' '' \
    'Package: *' 'Pin: origin "repo.i2pd.xyz"' 'Pin-Priority: -1' >"$stage/raspiblitz-i2pd" || return 1
  sudo install -d -m 755 /etc/apt/keyrings || return 1
  local apt_stage
  apt_stage=$(sudo mktemp -d /etc/apt/keyrings/.i2pd.XXXXXXXX) || return 1
  trap 'sudo rm -rf -- "$apt_stage"; rm -rf -- "$stage"' EXIT
  sudo install -m 644 "$stage/i2pd.gpg" "$stage/i2pd.list" "$stage/raspiblitz-i2pd" "$apt_stage/" || return 1
  sudo mv -f "$apt_stage/i2pd.gpg" "$keyring" || return 1
  sudo mv -f "$apt_stage/raspiblitz-i2pd" /etc/apt/preferences.d/raspiblitz-i2pd || return 1

  # Old RaspiBlitz installs trusted this dedicated keyring for every APT source.
  # Preserve it if it also contains a different primary key.
  if [ -f "$legacy" ]; then
    local keys
    keys=$(gpg --batch --homedir "$stage" --with-colons --show-keys "$legacy") || return 1
    if [ "$(awk -F: '$1=="pub" {pub=1} $1=="fpr" && pub {print $10; pub=0}' <<<"$keys")" = "$fingerprint" ]; then
      sudo rm -- "$legacy" || return 1
    else
      echo "# Preserved custom $legacy. If it contains the i2pd key, review its global APT trust." >&2
    fi
  fi
  sudo mv -f "$apt_stage/i2pd.list" "$list" || return 1
)

function bitcoinI2Pstatus {
  echo "# I2P related logs from the bitcoin debug log"
  echo "# Follow live with the command:"
  echo "sudo tail -n 1000 -f /mnt/hdd/app-data/bitcoin/debug.log | grep i2p"
  echo
  sudo cat /mnt/hdd/app-data/bitcoin/debug.log | grep i2p
  echo
  echo "# Running the command:"
  echo "bitcoin-cli -netinfo 4"
  echo
  bitcoin-cli -netinfo 4
  echo
  echo "# i2pd webconsole:"
  localip=$(hostname -I | awk '{print $1}')
  echo "http://${localip}:7070"
  echo "# Username: i2pd"
  echo "# Password: your passwordB"
  echo
}

echo "# Running: 'blitz.i2pd.sh $*'"

# make sure to be present in PATH
if ! echo "$PATH" | grep "/usr/sbin" >/dev/null; then
  export PATH=$PATH:/usr/sbin
  echo "PATH=\$PATH:/usr/sbin" | sudo tee -a /etc/profile
fi

if [ "$1" = "install" ]; then

  if dpkg-query -W -f='${db:Status-Status}\n' i2pd 2>/dev/null | grep -qx installed &&
     [ ! -f /etc/apt/sources.list.d/i2pd.list ]; then
    echo "# Keeping the installed i2pd package and its configured APT provider."
    exit 0
  fi
  add_repo || exit 1
  # Refresh all configured indexes together so dependency indexes are retained.
  sudo apt-get -o APT::Update::Error-Mode=any update || exit 1
  if ! dpkg-query -W -f='${db:Status-Status}\n' i2pd 2>/dev/null | grep -qx installed; then
    sudo apt-get install -y i2pd || exit 1
  fi
  exit 0
fi

if [ "$1" = "1" ] || [ "$1" = "on" ]; then

  if ! dpkg-query -W -f='${db:Status-Status}\n' i2pd 2>/dev/null | grep -qx installed; then
    /home/admin/config.scripts/blitz.i2pd.sh install || exit 1
  elif grep -Eq '^deb[[:space:]]+https://repo\.i2pd\.xyz/' /etc/apt/sources.list.d/i2pd.list 2>/dev/null; then
    # Repair an existing installation when provisioning a node after a code update.
    /home/admin/config.scripts/blitz.i2pd.sh install || exit 1
  fi

  if systemctl is-active --quiet i2pd.service; then
    echo "# i2pd.service is already active."
  else
    echo "# sudo systemctl enable i2pd"
    sudo systemctl enable i2pd
  fi

  echo "# i2pd config"
  sudo sed -i '/^debug=tor$/d' /mnt/hdd/app-data/bitcoin/bitcoin.conf
  /home/admin/config.scripts/blitz.conf.sh set debug tor /mnt/hdd/app-data/bitcoin/bitcoin.conf noquotes
  confAdd debug i2p /mnt/hdd/app-data/bitcoin/bitcoin.conf
  /home/admin/config.scripts/blitz.conf.sh set i2psam 127.0.0.1:7656 /mnt/hdd/app-data/bitcoin/bitcoin.conf noquotes
  /home/admin/config.scripts/blitz.conf.sh set i2pacceptincoming 1 /mnt/hdd/app-data/bitcoin/bitcoin.conf noquotes
  /home/admin/config.scripts/blitz.conf.sh set onlynet onion /mnt/hdd/app-data/bitcoin/bitcoin.conf noquotes
  confAdd onlynet i2p /mnt/hdd/app-data/bitcoin/bitcoin.conf
  PASSWORD_B=$(sudo cat /mnt/hdd/app-data/bitcoin/bitcoin.conf | grep rpcpassword | cut -c 13-)
  cat <<EOF | sudo tee /etc/i2pd/i2pd.conf
# i2pd settings for the RaspiBlitz
# for the defaults see:
# https://github.com/PurpleI2P/i2pd/blob/openssl/contrib/i2pd.conf
# Docs:
# https://i2pd.readthedocs.io/en/latest/user-guide/configuration/
loglevel = none
[http]
address=0.0.0.0
strictheaders = false
port = 7070
auth = true
user = i2pd
pass = ${PASSWORD_B}
[httpproxy]
enabled = false
[socksproxy]
enabled = false
[sam]
enabled = true
[bob]
enabled = false
[i2cp]
enabled = false
[i2pcontrol]
enabled = false
[upnp]
enabled = false
EOF

  sudo ufw allow 7070 comment "i2pd-webconsole"

  # Restart bitcoind and start i2p
  source <(/home/admin/_cache.sh get state)
  if [ "${state}" == "ready" ]; then
    echo "# Starting i2pd service ..."
    sudo systemctl start i2pd

    echo "# Restart bitcoind ..."
    sudo systemctl restart bitcoind 2>/dev/null
    sleep 10
  fi

  if i2pd --version; then
    echo "# Installed i2pd"
  else
    echo "# i2pd is not installed"
    exit 1
  fi

  # setting value in raspiblitz.conf
  /home/admin/config.scripts/blitz.conf.sh set i2pd "on"

  localip=$(hostname -I | awk '{print $1}')
  echo "# Config: /etc/i2pd/i2pd.conf"
  echo "# i2pd web console: ${localip}:7070"
  echo "# Monitor i2p in bitcoind:"
  echo "sudo tail -n 100 /mnt/hdd/app-data/bitcoin/debug.log | grep i2p"
  echo "bitcoin-cli -netinfo 4"

  exit 0
fi

if [ "$1" = "addseednodes" ]; then

  if ! sudo -u bitcoin bitcoin-cli -netinfo 4 | grep i2p; then
    /home/admin/config.scripts/blitz.i2pd.sh on || exit 1
  fi
  echo "Add 21 randomly selected I2P seed nodes from: https://github.com/bitcoin/bitcoin/blob/master/contrib/seeds/nodes_main.txt"
  echo "Monitor in a new terminal with:"
  echo "watch sudo -u bitcoin bitcoin-cli -netinfo 4"
  echo "This will take some time ..."

  # Fetch and filter the list of seed nodes
  i2pSeedNodeList=$(curl -sS https://raw.githubusercontent.com/bitcoin/bitcoin/master/contrib/seeds/nodes_main.txt | grep .b32.i2p:0)

  # Shuffle the list and pick the first 21 nodes
  selectedNodes=$(echo "$i2pSeedNodeList" | shuf | head -n 21)

  # Add each selected node
  for i2pSeedNode in ${selectedNodes}; do
    echo "# Add i2p seed node: ${i2pSeedNode} by running:"
    echo "bitcoin-cli addnode $i2pSeedNode onetry"
    sudo -u bitcoin bitcoin-cli addnode "$i2pSeedNode" "onetry"
  done
  
  echo
  echo "# Display bitcoin-cli -netinfo 4"
  sudo -u bitcoin bitcoin-cli -netinfo 4

  exit 0
fi

# switch off
if [ "$1" = "0" ] || [ "$1" = "off" ]; then

  echo "# stop & remove systemd service"
  sudo systemctl stop i2pd 2>/dev/null
  sudo systemctl disable i2pd.service

  echo "# Uninstall with apt"
  sudo apt remove -y i2pd

  echo "# Remove settings from bitcoind"
  sudo sed -i '/^debug=tor$/d' /mnt/hdd/app-data/bitcoin/bitcoin.conf
  /home/admin/config.scripts/blitz.conf.sh delete debug /mnt/hdd/app-data/bitcoin/bitcoin.conf noquotes
  /home/admin/config.scripts/blitz.conf.sh set debug tor /mnt/hdd/app-data/bitcoin/bitcoin.conf noquotes
  /home/admin/config.scripts/blitz.conf.sh delete i2psam /mnt/hdd/app-data/bitcoin/bitcoin.conf noquotes
  /home/admin/config.scripts/blitz.conf.sh delete i2pacceptincoming /mnt/hdd/app-data/bitcoin/bitcoin.conf noquotes
  /home/admin/config.scripts/blitz.conf.sh delete onlynet /mnt/hdd/app-data/bitcoin/bitcoin.conf noquotes
  /home/admin/config.scripts/blitz.conf.sh set onlynet onion /mnt/hdd/app-data/bitcoin/bitcoin.conf noquotes

  sudo rm /etc/systemd/system/i2pd.service

  sudo ufw delete allow 7070

  if ! i2pd --version 2>/dev/null; then
    echo "# OK - i2pd is not installed now"
  else
    echo "# i2pd is still installed"
    exit 1
  fi

  # setting value in raspiblitz.conf
  /home/admin/config.scripts/blitz.conf.sh set i2pd "off"

  exit 0
fi

if [ "$1" = "status" ]; then
  bitcoinI2Pstatus
  exit 0
fi

echo "# FAIL - Unknown Parameter $1"
exit 1
